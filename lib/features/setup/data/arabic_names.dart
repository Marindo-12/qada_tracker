/// Best-effort gender guess for a typed first name.
///
/// Returns `true` for male, `false` for female, or `null` if the name
/// isn't recognized (unknown, empty, or matched in neither list). Callers
/// should treat `null` as "keep the current/default icon" rather than
/// guessing.
bool? isMaleArabicName(String rawName) {
  final name = _normalize(rawName);
  if (name.isEmpty) return null;

  // Only check the first word: people sometimes type a full name
  // ("محمد العلي"), and the first token is the actual given name.
  final firstToken = name.split(RegExp(r'\s+')).first;

  final isMale = maleArabicNames.contains(firstToken) || maleArabicNames.contains(name);
  final isFemale = femaleArabicNames.contains(firstToken) || femaleArabicNames.contains(name);

  if (isMale && !isFemale) return true;
  if (isFemale && !isMale) return false;
  return null; // unknown or ambiguous
}

String _normalize(String input) {
  var s = input.trim();
  if (s.isEmpty) return s;

  // Strip Arabic diacritics (tashkeel) and tatweel.
  s = s.replaceAll(RegExp(r'[\u064B-\u065F\u0670\u0640]'), '');

  // Normalize alef variants to bare alef, and taa marbuta stays as-is
  // (kept distinct since it's meaningful for gender in Arabic).
  s = s.replaceAll(RegExp('[إأآا]'), 'ا');

  // Drop a leading definite article some people type before their name.
  if (s.startsWith('ال') && s.length > 3) {
    s = s.substring(2);
  }

  return s;
}