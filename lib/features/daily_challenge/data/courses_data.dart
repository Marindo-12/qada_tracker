List<FiqhQuestion> get _allQuestions => [...fiqhQuestions, ...extraQuestions];

FiqhQuestion? questionById(int id) {
  for (final q in _allQuestions) {
    if (q.id == id) return q;
  }
  return null;
}

/// Final-challenge pool for a course (original bank + extra questions).
List<FiqhQuestion> questionsForCourse(Course course) =>
    _allQuestions.where((q) => q.category == course.category).toList();